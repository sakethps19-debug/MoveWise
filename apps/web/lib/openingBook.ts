/**
 * P1 "honest short-game review": identifying the opening family/variation
 * a real game actually reached, and offering a real, textbook strategic
 * idea for it when one is available — never a fabricated claim about
 * what this specific learner did right or wrong. Deliberately
 * conservative: an opening is only ever named when the played SAN
 * sequence is an exact prefix match against a known line (the longest
 * one that matches, so a specific variation is preferred over its parent
 * family when both apply) — no fuzzy or partial matching, so a genuinely
 * unrecognized sequence returns nothing rather than a guess.
 *
 * The move-name/ECO data itself comes from the real CC0
 * lichess-org/chess-openings dataset (see
 * docs/content-sources.md/`packages/content/openings/chess-openings.json`,
 * generated by scripts/import-chess-openings.ts) — 2,337 lines, each
 * chess-rules-verified legal, capped at 10 plies so this never becomes
 * the "memorization of long forced lines for beginners" the founding
 * brief explicitly warns against.
 *
 * The per-opening strategic `idea` text is NOT part of that dataset (the
 * CC0 set only has eco/name/move-facts, no prose) — it's original
 * MoveWise writing, curated for a modest set of the most common openings
 * a beginner/intermediate learner will actually reach. An identified
 * opening outside that curated set still gets an accurate name (backed
 * by real, licensed data) but an empty `idea` — never a fabricated
 * strategic claim for an opening nobody has actually written about here.
 */
import openingsData from "../../../packages/content/openings/chess-openings.json";

interface OpeningEntry {
  eco: string;
  name: string;
  sanMoves: string[];
}

const OPENING_BOOK = openingsData as OpeningEntry[];

