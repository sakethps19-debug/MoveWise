export interface IdentifiedOpening {
  name: string;
  eco: string;
  /** Original MoveWise strategic note, or "" when this specific opening isn't in the curated idea set yet — never a fabricated claim. */
  idea: string;
}

function baseFamilyName(fullName: string): string {
  return fullName.split(":")[0]!.trim();
}

/**
 * Exact-prefix match only — the longest matching entry wins, so a more
 * specific variation is preferred over its parent family whenever the
 * played moves actually support it. `sanMoves` is every SAN move
 * actually played, in order, both colors interleaved (i.e.
 * `review.moves.map(m => m.playedMove)`).
 */
export function identifyOpening(sanMoves: string[]): IdentifiedOpening | null {
  let best: OpeningEntry | null = null;
  for (const entry of OPENING_BOOK) {
    if (entry.sanMoves.length > sanMoves.length) continue;
    const isPrefix = entry.sanMoves.every((san, i) => sanMoves[i] === san);
    if (isPrefix && (!best || entry.sanMoves.length > best.sanMoves.length)) best = entry;
  }
  if (!best) return null;
  return { name: best.name, eco: best.eco, idea: IDEA_BY_BASE_NAME[baseFamilyName(best.name)] ?? "" };
}
